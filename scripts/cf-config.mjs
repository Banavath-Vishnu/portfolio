// Generates wrangler.jsonc (Cloudflare config), wrangler.dev.jsonc (used by `next dev`) and .dev.vars (local secrets for `npm run preview`)
// from .env.local / .env — so .env.local is the only file you edit.
//   npm run cf:config      (also runs automatically before dev, preview and deploy)
// In CI (Cloudflare Workers Builds / GitHub Actions) set the same names as environment variables.

import { existsSync, writeFileSync } from 'node:fs';

for (const file of ['.env.local', '.env']) {
  if (existsSync(file)) process.loadEnvFile(file); // doesn't override variables already set
}

const env = (name, fallback = '') => (process.env[name] || fallback).trim();
const worker = env('CF_WORKER_NAME', 'vishnu-portfolio');
const d1Name = env('CF_D1_DATABASE_NAME', `${worker}-db`);
// Local dev and preview work with any id (Wrangler keeps a local SQLite copy); deploys need the real one.
const d1Id = env('CF_D1_DATABASE_ID', '00000000-0000-0000-0000-000000000000');
const accountId = env('CF_ACCOUNT_ID');

const config = {
  $schema: 'node_modules/wrangler/config-schema.json',
  name: worker,
  // worker.js wraps the OpenNext app (.open-next/worker.js) with the edge page cache.
  main: 'worker.js',
  compatibility_date: '2026-10-01',
  compatibility_flags: ['nodejs_compat', 'global_fetch_strictly_public'],
  ...(accountId ? { account_id: accountId } : {}),
  // html_handling none: serve files like the Google verification .html exactly at their URL (no redirect).
  assets: { directory: '.open-next/assets', binding: 'ASSETS', html_handling: 'none' },
  observability: { enabled: true },
  // Gives worker.js a unique ID per deployment (used in the edge cache key).
  version_metadata: { binding: 'CF_VERSION_METADATA' },
  d1_databases: [{ binding: 'DB', database_name: d1Name, database_id: d1Id }],
  // Non-secret runtime settings. CLOUDINARY_API_SECRET is a secret: .dev.vars locally, `npm run cf:secrets` for production.
  vars: Object.fromEntries(['CLOUDINARY_CLOUD_NAME', 'CLOUDINARY_API_KEY', 'CLOUDINARY_FOLDER', 'SITE_TIMEZONE', 'SITE_URL', 'GOOGLE_SITE_VERIFICATION', 'BING_SITE_VERIFICATION'].map((k) => [k, env(k)]).filter(([, v]) => v)),
};

const header = '// GENERATED by scripts/cf-config.mjs from .env.local — edit .env.local, not this file.\n';
writeFileSync('wrangler.jsonc', header + JSON.stringify(config, null, 2) + '\n');

// `next dev` only needs the bindings (D1 + vars), so it uses this copy without the build-output entries.
const { assets, main, ...devConfig } = config;
writeFileSync('wrangler.dev.jsonc', header + JSON.stringify(devConfig, null, 2) + '\n');

// Secrets for `wrangler dev` / `npm run preview` (Wrangler reads .dev.vars). Production secrets are
// uploaded separately with `npm run cf:secrets`.
const secrets = ['ADMIN_PASSWORD', 'SESSION_SECRET', 'CLOUDINARY_API_SECRET'].filter((k) => env(k)).map((k) => `${k}=${JSON.stringify(env(k))}`);
writeFileSync('.dev.vars', `# GENERATED by scripts/cf-config.mjs — local only, never commit.\n${secrets.join('\n')}\n`);

const placeholderId = d1Id.startsWith('00000000');
const cloudinary = env('CLOUDINARY_CLOUD_NAME') ? `Cloudinary "${env('CLOUDINARY_CLOUD_NAME')}"` : 'Cloudinary not set (uploads off)';
console.log(`wrangler.jsonc → worker "${worker}", D1 "${d1Name}"${placeholderId ? ' (local id — set CF_D1_DATABASE_ID before deploying)' : ''}, ${cloudinary}`);
