// Cloudflare Worker entry: the OpenNext (Next.js) app, with an edge page cache in front of it.
//
// Public pages (home, /blog, posts, projects, sitemap, robots, feed) are cached in Cloudflare's edge cache for
// anonymous visitors, so repeat visits skip rendering and the database entirely. The cache key includes a
// "content version" (and the deployment ID): every admin change, comment or moderation bumps it (lib/db.js → bumpContentVersion), and a
// scheduled post going live changes it too — so visitors always see current content, with no manual purging.
// Never cached: anything with the admin cookie, non-GET requests, query strings, Next.js client navigations (RSC),
// server actions, the API and admin routes, and responses that set cookies.
//
// Used by `npm run preview` / `npm run deploy` (wrangler.jsonc → main). `npm run dev` runs Next directly, uncached.

// @ts-ignore — generated by `opennextjs-cloudflare build`
import { default as handler } from './.open-next/worker.js';

const CACHEABLE = /^\/(?:|blog|blog\/[^/]+|projects\/[^/]+|sitemap\.xml|robots\.txt|feed\.xml|llms\.txt|llms-full\.txt)$/;
const TTL = 3600; // seconds a cached page may be served before it's rebuilt anyway
const VERSION_TTL = 3_000; // ms each Worker instance reuses the version it looked up

let memo = { at: 0, value: null };

// One tiny query (at most every 3s per instance): the content version, plus how many posts are live right now,
// so a scheduled post publishing itself also produces a new cache key.
async function contentVersion(env) {
  if (Date.now() - memo.at < VERSION_TTL) return memo.value;
  let value = null;
  try {
    const row = await env.DB.prepare(
      `SELECT (SELECT value FROM meta WHERE key = 'content_version') AS v,
              (SELECT COUNT(*) FROM posts WHERE published AND (published_at IS NULL OR published_at <= ?)) AS live`,
    ).bind(new Date().toISOString()).first();
    value = `${row?.v ?? 0}.${row?.live ?? 0}`;
  } catch {
    value = null; // database not set up yet: don't cache
  }
  memo = { at: Date.now(), value };
  return value;
}

function bypass(request, url) {
  if (request.method !== 'GET' || url.search || !CACHEABLE.test(url.pathname)) return true;
  if (/(?:^|;\s*)admin_session=/.test(request.headers.get('cookie') || '')) return true; // you see live content
  // Client-side navigations, router refreshes and server actions always go to the app.
  return Boolean(request.headers.get('rsc') || request.headers.get('next-router-state-tree') || request.headers.get('next-action'));
}

const withHeader = (res, status) => {
  const out = new Response(res.body, res);
  out.headers.set('X-Edge-Cache', status);
  // Browsers re-check each time (cheap: it's served from the edge); only Cloudflare holds the copy.
  out.headers.set('Cache-Control', 'public, max-age=0, must-revalidate');
  return out;
};

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    // A form submission (comment, admin save…) may change content: once it's done, look the version up afresh,
    // so whoever made the change sees it on their very next page load.
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      const res = await handler.fetch(request, env, ctx);
      memo = { at: 0, value: null };
      return res;
    }
    if (bypass(request, url)) return handler.fetch(request, env, ctx);

    const version = await contentVersion(env);
    if (!version) return handler.fetch(request, env, ctx);

    const cache = caches.default;
    // The deployment ID is part of the key too: each deploy starts with a fresh cache, so no visitor ever gets a
    // cached page that points at the previous build's (now deleted) script files.
    const deploy = env.CF_VERSION_METADATA?.id || 'dev';
    const key = new Request(`${url.origin}${url.pathname}?__v=${version}&__d=${deploy}`, { method: 'GET' });
    const hit = await cache.match(key);
    if (hit) return withHeader(hit, 'HIT');

    const res = await handler.fetch(request, env, ctx);
    if (res.status === 200 && !res.headers.has('set-cookie')) {
      const copy = new Response(res.clone().body, res);
      copy.headers.set('Cache-Control', `public, s-maxage=${TTL}`);
      ctx.waitUntil(cache.put(key, copy));
      return withHeader(res, 'MISS');
    }
    return res;
  },
};
